#!/usr/bin/env node
/**
 * Builds the REST API reference from the FastAPI app itself:
 *   - docs/api/openapi.json  (the full OpenAPI schema; served live at /api/openapi.json and /api/docs)
 *   - docs/api/README.md     (every endpoint grouped by area, with the drivers that serve it)
 *
 *   node scripts/generate-api-docs.mjs
 * Loads backend/app/main.py once per hypervisor driver with Python (PYTHON env var, else backend/.venv/bin/python,
 * else python3); no server is started and no host is contacted.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BACKEND = join(ROOT, "backend");
const OUT = join(ROOT, "docs/api");
const DRIVERS = ["proxmox", "native_ubuntu"];
const LABEL = { proxmox: "Proxmox VE", native_ubuntu: "SolarOS" };
const python = process.env.PYTHON || (existsSync(join(BACKEND, ".venv/bin/python")) ? join(BACKEND, ".venv/bin/python") : "python3");

const DUMP = `
import json, os, tempfile
os.environ.setdefault("STORAGE_ROOT", tempfile.mkdtemp())
os.environ.setdefault("JWT_SECRET", "x" * 32)
os.environ.setdefault("ADMIN_PASSWORD", "docs")
from app.main import app
print(json.dumps(app.openapi()))
`;

function schema(driver) {
  const r = spawnSync(python, ["-c", DUMP], { cwd: BACKEND, env: { ...process.env, HYPERVISOR_DRIVER: driver }, encoding: "utf8", maxBuffer: 64 << 20 });
  if (r.status !== 0) throw new Error(`${driver}: ${r.stderr.trim().split("\n").slice(-3).join("\n")}`);
  return JSON.parse(r.stdout);
}

const schemas = Object.fromEntries(DRIVERS.map((d) => [d, schema(d)]));
const METHODS = ["get", "post", "put", "patch", "delete"];
const rows = new Map(); // "METHOD path" -> {method, path, tag, summary, drivers}
for (const d of DRIVERS) {
  for (const [path, ops] of Object.entries(schemas[d].paths)) {
    for (const m of METHODS) {
      if (!ops[m]) continue;
      const key = `${m.toUpperCase()} ${path}`;
      const row = rows.get(key) ?? { method: m.toUpperCase(), path, tag: ops[m].tags?.[0] ?? "other", summary: ops[m].summary ?? "", drivers: [] };
      row.drivers.push(d);
      rows.set(key, row);
    }
  }
}

const byTag = new Map();
for (const r of rows.values()) byTag.set(r.tag, [...(byTag.get(r.tag) ?? []), r]);
const tags = [...byTag.keys()].sort();
const cell = (s) => s.replace(/\|/g, "\\|");
let md = `# SolarDeck REST API\n\n`;
md += `Generated by \`node scripts/generate-api-docs.mjs\` from the backend itself: ${rows.size} endpoints in ${tags.length} areas. `;
md += `A running server also serves the interactive reference at \`/api/docs\` and the schema at \`/api/openapi.json\`; the full schema is in [openapi.json](openapi.json).\n\n`;
md += `Every endpoint needs a signed-in session (the \`pos_session\` cookie or \`Authorization: Bearer <token>\` from \`POST /api/auth/login\`) unless noted; destructive actions also need a step-up token (\`X-Step-Up-Token\`). Extra accounts are limited by their role (Settings → Privilege & Security → Users & Roles).\n\n`;
md += `## Areas\n\n${tags.map((t) => `- [${t}](#${t.replace(/_/g, "-").toLowerCase()}) (${byTag.get(t).length})`).join("\n")}\n`;
for (const t of tags) {
  md += `\n## ${t.replace(/_/g, "-")}\n\n| Method | Path | Summary | Drivers |\n|---|---|---|---|\n`;
  for (const r of byTag.get(t).sort((a, b) => a.path.localeCompare(b.path) || METHODS.indexOf(a.method.toLowerCase()) - METHODS.indexOf(b.method.toLowerCase()))) {
    const drv = r.drivers.length === DRIVERS.length ? "both" : r.drivers.map((d) => LABEL[d]).join(", ");
    md += `| ${r.method} | \`${cell(r.path)}\` | ${cell(r.summary)} | ${drv} |\n`;
  }
}

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "openapi.json"), JSON.stringify(schemas.proxmox, null, 1) + "\n");
writeFileSync(join(OUT, "README.md"), md);
console.log(`docs/api: ${rows.size} endpoints, ${tags.length} areas`);
